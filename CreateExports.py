def export_condition_coverage_gaps(
    footpath_polygons,
    condition_events,
    null_condition_events,
    output_feature_class,
):
    """Export only polygons containing points with a null Condition value."""
    status_field = "Condition_Data_Status"
    del condition_events
    condition_field = next(
        (
            field.name
            for field in arcpy.ListFields(null_condition_events)
            if field.name.lower() == "condition"
        ),
        None,
    )
    if condition_field is None:
        raise arcpy.ExecuteError(
            f"The null-condition dataset '{os.path.basename(null_condition_events)}' "
            "does not contain a Condition field."
        )

    null_points_layer = arcpy.CreateUniqueName(
        "NullConditionPoints", "in_memory"
    )
    null_condition_join = arcpy.CreateUniqueName(
        "NullConditionCoverageJoin", arcpy.env.scratchGDB
    )
    try:
        condition_field_delimited = arcpy.AddFieldDelimiters(
            null_condition_events, condition_field
        )
        field = next(
            field
            for field in arcpy.ListFields(null_condition_events)
            if field.name == condition_field
        )
        if field.type == "String":
            where_clause = (
                f"{condition_field_delimited} IS NULL OR "
                f"UPPER({condition_field_delimited}) = 'NULL'"
            )
        else:
            where_clause = f"{condition_field_delimited} IS NULL"
        arcpy.management.MakeFeatureLayer(
            null_condition_events, null_points_layer, where_clause
        )
        arcpy.analysis.SpatialJoin(
            target_features=footpath_polygons,
            join_features=null_points_layer,
            out_feature_class=null_condition_join,
            join_operation="JOIN_ONE_TO_ONE",
            join_type="KEEP_COMMON",
            match_option="CONTAINS",
        )
        if arcpy.Exists(output_feature_class):
            arcpy.management.Delete(output_feature_class)
        arcpy.management.CopyFeatures(
            null_condition_join, output_feature_class
        )
        arcpy.management.AddField(
            output_feature_class, status_field, "TEXT", field_length=20
        )
        arcpy.management.CalculateField(
            output_feature_class,
            status_field,
            repr("Null condition"),
            "PYTHON3",
        )
    finally:
        for temporary_dataset in (null_points_layer, null_condition_join):
            if arcpy.Exists(temporary_dataset):
                arcpy.management.Delete(temporary_dataset)

    output_count = int(arcpy.management.GetCount(output_feature_class)[0])
    arcpy.AddMessage(
        f"Exported {output_count} footpath polygon(s) with no or partial "
        f"condition data to {os.path.basename(output_feature_class)}."
    )


